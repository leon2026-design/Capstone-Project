const PARSER_INPUT_FOLDER =
  PropertiesService.getScriptProperties()
    .getProperty("PARSER_INPUT_FOLDER");

const PARSER_OUTPUT_FOLDER =
  PropertiesService.getScriptProperties()
    .getProperty("PARSER_OUTPUT_FOLDER");

function processNewPDFs() {
  const folder = DriveApp.getFolderById(PARSER_INPUT_FOLDER);
  const targetFolder = DriveApp.getFolderById(PARSER_OUTPUT_FOLDER); 

  const files = folder.getFiles();
  const started = Date.now();
  const stats = {processed: 0, failed: 0, unsupported: 0, deferred: false};
  while(files.hasNext()){
    // Reserve time for review synchronization and the output sheet before the GAS limit.
    if (Date.now() - started > 240000) { stats.deferred = true; break; }
    const file = files.next();
    try {
      const type = file.getMimeType();
      const word = ["application/msword",
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"].includes(type);
      if (type === MimeType.CSV) continue;
      if (type !== "application/pdf" && !word) { stats.unsupported++; continue; }
      // Conversion is temporary; the original Word file remains the source.
      parseUndefinedFile(file, () => word ? marketingWordPdfBlob_(file) : file.getBlob(), targetFolder);
      stats.processed++;
    } catch (error) {
      stats.failed++;
      logMarketingFailure_("REPORT", file.getId(), error);
    }
  }
  // Preserve the existing standalone CSV extraction, without a second contact import.
  try { processCsvFiles(folder, targetFolder); } catch (error) {
    stats.failed++;
    logMarketingFailure_("CSV", PARSER_INPUT_FOLDER, error);
  }
  return stats;
}

function marketingWordPdfBlob_(file) {
  const converted = Drive.Files.copy({
    title: "MA temporary conversion",
    mimeType: "application/vnd.google-apps.document"
  }, file.getId(), {convert: true});
  try {
    return DriveApp.getFileById(converted.id).getAs("application/pdf");
  } finally {
    DriveApp.getFileById(converted.id).setTrashed(true);
  }
}

/**
 * Finds CSV files, parses them, adds them to the spreadsheet, and moves them to the target folder.
 */
function processCsvFiles(folder, targetFolder) {
  const csvFiles = folder.getFilesByType(MimeType.CSV);
  const ss = SpreadsheetApp.openByUrl("https://docs.google.com/spreadsheets/d/" + SPREADSHEET_DATA_EXTRACTION + "/edit");

  while (csvFiles.hasNext()) {
    const file = csvFiles.next();
    const fileName = file.getName().replace(/\.csv$/i, "");
    
    // Parse the CSV content
    const csvData = Utilities.parseCsv(file.getBlob().getDataAsString());
    
    if (csvData.length > 0) {
      let sheet = ss.getSheetByName(fileName);
      
      // If sheet exists, maybe clear it or just create a new one with a unique name
      if (sheet) {
        // Option A: Clear existing (Uncomment if preferred)
        // sheet.clear(); 
        
        // Option B: Create unique name (Standard approach)
        sheet = ss.insertSheet(fileName + "_" + new Date().getTime());
      } else {
        sheet = ss.insertSheet(fileName);
      }

      // Write the CSV data to the sheet
      sheet.getRange(1, 1, csvData.length, csvData[0].length).setValues(csvData);
      sheet.getDataRange().setWrapStrategy(SpreadsheetApp.WrapStrategy.WRAP);
    }

    // Move to target folder
    file.moveTo(targetFolder);
    console.log("Processed CSV: " + fileName);
  }
}

/**
 * Parses the file using headers generated by gemini itself.
 */
function parseUndefinedFile(file, blob, targetFolder) {
  const lock = LockService.getScriptLock();
  lock.waitLock(10000);
  try {
    return parseMarketingReportUnlocked_(file, blob, targetFolder);
  } finally { lock.releaseLock(); }
}

function parseMarketingReportUnlocked_(file, blob, targetFolder) {
  const props = PropertiesService.getScriptProperties();
  const checkpointKey = "MA_REPORT_" + file.getId();
  const saved = props.getProperty(checkpointKey);
  const ss = SpreadsheetApp.openById(SPREADSHEET_DATA_EXTRACTION);
  if (saved) {
    const checkpoint = JSON.parse(saved);
    const sheet = ss.getSheets().find(tab => tab.getSheetId() === checkpoint.sheetId);
    if (!sheet || sheet.getLastRow() < 2) throw new Error("Missing checkpoint report tab: " + file.getId());
    if (checkpoint.state !== "IMPORTED") {
      importReportContactsUnlocked_([sheet.getSheetId()]);
      SpreadsheetApp.flush();
      props.setProperty(checkpointKey, JSON.stringify({sheetId: sheet.getSheetId(), state: "IMPORTED"}));
    }
    file.moveTo(targetFolder);
    return sheet.getSheetId();
  }
  const response = geminiParsePDFUndefined(typeof blob === "function" ? blob() : blob);
  if (response.getResponseCode() !== 200) {
    throw new Error("PDF extraction failed (HTTP " + response.getResponseCode() + "): " + file.getName());
  }
  const result = JSON.parse(response.getContentText());
  const candidate = (result.candidates || [])[0];
  if (!candidate || !candidate.content ||
      (candidate.finishReason && candidate.finishReason !== "STOP")) {
    throw new Error("Incomplete PDF extraction: " + file.getName());
  }
  const text = (candidate.content.parts || [])
    .map(part => part.text || "").join("").trim();
  const data = JSON.parse(text.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, ""));
  if (!Array.isArray(data) || !data.length) {
    throw new Error("No report rows returned: " + file.getName());
  }

  // Provenance comes from Drive/the script, never from Gemini.
  const extractedAt = new Date().toISOString();
  const owned = new Set(["reportsourceid", "reportsourceurl", "reportextractedat"]);
  const records = data.map((record, i) => {
    if (!record || typeof record !== "object" || Array.isArray(record)) {
      throw new Error("Invalid report record " + (i + 1));
    }
    const cleaned = {};
    for (const [header, value] of Object.entries(record)) {
      if (owned.has(normalizeKey(header))) continue;
      const canonical = canonicalCampaignReportHeader(header);
      if (!canonical || Object.prototype.hasOwnProperty.call(cleaned, canonical) ||
          (value !== null && typeof value === "object")) {
        throw new Error("Invalid or duplicate report field: " + header);
      }
      Object.defineProperty(cleaned, canonical, {
        value: value == null ? "" : value, enumerable: true, configurable: true
      });
    }
    if (!Object.keys(cleaned).length) throw new Error("Empty report record " + (i + 1));
    return Object.assign(cleaned, {
      "Report Source ID": file.getId(),
      "Report Source URL": file.getUrl(),
      "Report Extracted At": extractedAt
    });
  });

  const name = file.getName().replace(/\.(pdf|docx?)$/i, "")
    .replace(/[\[\]:*?\/\\]/g, " ").trim().slice(0, 45) || "Report";
  let sheet = ss.getSheetByName(name);
  if (sheet && sheet.getLastRow() > 1) {
    const values = sheet.getDataRange().getDisplayValues();
    const sourceColumn = values[0].map(normalizeKey).indexOf("reportsourceid");
    if (sourceColumn >= 0 && values.slice(1).some(row => row[sourceColumn] && row[sourceColumn] !== file.getId()))
      sheet = ss.getSheetByName(name + " " + file.getId()) || ss.insertSheet(name + " " + file.getId());
  }
  sheet = sheet || ss.insertSheet(name);

  // Write the extracted records using the existing header mapping.
  appendCampaignReportRows(sheet, records);

  // Arrange and format this specific report.
  formatCampaignReportSheet(sheet);

  SpreadsheetApp.flush();
  props.setProperty(checkpointKey, JSON.stringify({sheetId: sheet.getSheetId(), state: "EXTRACTED"}));

  // Import this exact tab automatically.
  importReportContactsUnlocked_([sheet.getSheetId()]);

  SpreadsheetApp.flush();
  props.setProperty(checkpointKey, JSON.stringify({sheetId: sheet.getSheetId(), state: "IMPORTED"}));

  // Move the PDF only after contact importing completes.
  // If importing throws an error, the PDF stays in the input folder.
  file.moveTo(targetFolder);

  return sheet.getSheetId();
}

// Preserve the existing dynamic extraction; normalize only known header labels.
function canonicalCampaignReportHeader(header) {
  const text = String(header == null ? "" : header).trim();
  const key = normalizeKey(text);
  const special = {
    name: "Name / DJ Alias", fullname: "Name / DJ Alias", contactname: "Name / DJ Alias",
    namedjalias: "Name / DJ Alias", fave: "Favorite Track", favourite: "Favorite Track",
    favoritetrack: "Favorite Track", favouritetrack: "Favorite Track",
    favoriteremix: "Favorite Track", favouriteremix: "Favorite Track",
    campaignstatus: "Campaign Status", status: "Campaign Status",
    campaignrelease: "Campaign / Release", campaignname: "Campaign / Release",
    reportgeneratedat: "Report Generated At", activitytime: "Activity Time",
    reportsourceid: "Report Source ID", reportsourceurl: "Report Source URL",
    reportextractedat: "Report Extracted At", stateregion: "State/Region"
  };
  return (Object.prototype.hasOwnProperty.call(special, key) ? special[key] : "") ||
    buildHeaderAliasLookup().get(key) || text;
}

// Collect fields from EVERY record and align writes with any existing columns.
function appendCampaignReportRows(sheet, records) {
  const width = sheet.getLastColumn();
  const headers = width ? sheet.getRange(1, 1, 1, width).getDisplayValues()[0] : [];
  const positions = new Map();
  const key = header => normalizeKey(canonicalCampaignReportHeader(header));
  headers.forEach((header, i) => {
    const k = key(header);
    if (!k || positions.has(k)) throw new Error("Blank or duplicate report header: " + header);
    positions.set(k, i);
  });
  records.forEach(record => Object.keys(record).forEach(header => {
    const k = key(header);
    if (!positions.has(k)) {
      positions.set(k, headers.length);
      headers.push(header);
    }
  }));
  const literal = value => typeof value === "string" && value.startsWith("=") ? "'" + value : value;
  let rows = records.map(record => {
    const row = Array(headers.length).fill("");
    Object.entries(record).forEach(([header, value]) => row[positions.get(key(header))] = literal(value));
    return row;
  });
  // An interrupted write before its checkpoint must not append the same extraction again.
  const extractedAt = positions.get("reportextractedat");
  const fingerprint = row => JSON.stringify(headers.map((_, i) => i === extractedAt ? "" : String(row[i] == null ? "" : row[i]).replace(/^'(?==)/, "")));
  const seen = new Set(sheet.getLastRow() > 1 ?
    sheet.getRange(2, 1, sheet.getLastRow() - 1, Math.max(1, width)).getDisplayValues().map(fingerprint) : []);
  rows = rows.filter(row => {
    const key = fingerprint(row);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  if (!rows.length) return;
  const start = Math.max(2, sheet.getLastRow() + 1);
  if (headers.length > sheet.getMaxColumns())
    sheet.insertColumnsAfter(sheet.getMaxColumns(), headers.length - sheet.getMaxColumns());
  if (start + rows.length - 1 > sheet.getMaxRows())
    sheet.insertRowsAfter(sheet.getMaxRows(), start + rows.length - 1 - sheet.getMaxRows());
  if (headers.length > width)
    sheet.getRange(1, width + 1, 1, headers.length - width).setValues([headers.slice(width).map(literal)]);
  sheet.getRange(start, 1, rows.length, headers.length).setValues(rows);
}

