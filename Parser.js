  /**
   * Normalize header labels and reorder complete columns.
   * Preserve unfamiliar fields and existing data.
   */
  function formatCampaignReportSheet(sheet) {
    const width = sheet.getLastColumn();
    if (!width) return;

    const headers = sheet
      .getRange(1, 1, 1, width)
      .getDisplayValues()[0]
      .map(canonicalCampaignReportHeader);

    // Stop before changing anything if headers are ambiguous.
    const keys = headers.map(normalizeKey);

    if (
      keys.some(key => !key) ||
      new Set(keys).size !== keys.length
    ) {
      throw new Error(
        "Blank or duplicate report headers in " + sheet.getName()
      );
    }

    // Locate the actual header matching each preferred label.
    const findHeader = label =>
      headers.find(
        header => normalizeKey(header) === normalizeKey(label)
      );

    const front = CAMPAIGN_REPORT_COLUMN_ORDER
      .map(findHeader)
      .filter(Boolean);

    const source = CAMPAIGN_REPORT_SOURCE_COLUMNS
      .map(findHeader)
      .filter(Boolean);

    // Keep additional fields between the main fields and source fields.
    const known = new Set([...front, ...source]);

    const extra = headers.filter(header => !known.has(header));

    const ordered = [...front, ...extra, ...source];

    // Rename headers only. Do not rewrite existing data rows.
    sheet
      .getRange(1, 1, 1, width)
      .setValues([headers.map(asLiteralCellValue)]);

    // Move complete columns, keeping their contents together.
    ordered.forEach((header, destination) => {
      const current = headers.indexOf(header);

      if (current === destination) return;

      sheet.moveColumns(
        sheet.getRange(1, current + 1, 1, 1),
        destination + 1
      );

      // Track the updated positions after each move.
      headers.splice(
        destination,
        0,
        headers.splice(current, 1)[0]
      );
    });

    sheet
      .getRange(1, 1, 1, width)
      .setFontWeight("bold");

    sheet.setFrozenRows(1);

    sheet
      .getDataRange()
      .setWrapStrategy(SpreadsheetApp.WrapStrategy.WRAP);

    // Keep the source URL visible, but hide technical fields.
    ["Report Source ID", "Report Extracted At"].forEach(header => {
      const index = headers.indexOf(header);

      if (index !== -1) {
        sheet.hideColumns(index + 1);
      }
    });
  }

