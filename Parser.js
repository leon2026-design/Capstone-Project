// Caller holds the script lock. Base64 chunks keep Sheets from reinterpreting JSON text.
function marketingStageSection_(job, index, savedAt, rows) {
  const ss = SpreadsheetApp.openById(SPREADSHEET_DATA_EXTRACTION);
  let sheet = ss.getSheetByName(MARKETING_STAGING_SHEET);
  if (!sheet) {
    sheet = ss.insertSheet(MARKETING_STAGING_SHEET);
    sheet.getRange(1, 1, 1, MARKETING_STAGING_HEADERS.length).setValues([MARKETING_STAGING_HEADERS]);
  }
  const key = marketingStagingKey_(job);
  const encoded = Utilities.base64Encode(JSON.stringify(rows), Utilities.Charset.UTF_8);
  const row = [key, index, savedAt, rows.length];
  for (let i = 0; i < encoded.length; i += MARKETING_STAGING_CHUNK)
    row.push("b64:" + encoded.slice(i, i + MARKETING_STAGING_CHUNK));
  const last = sheet.getLastRow();
  const width = Math.max(row.length, sheet.getLastColumn());
  let target = last + 1;
  if (last > 1) {
    const found = sheet.getRange(2, 1, last - 1, 2).getValues()
      .findIndex(existing => existing[0] === key && Number(existing[1]) === index);
    if (found >= 0) target = found + 2;
  }
  if (width > sheet.getMaxColumns()) sheet.insertColumnsAfter(sheet.getMaxColumns(), width - sheet.getMaxColumns());
  ensureSheetRowCapacity(sheet, target);
  sheet.getRange(target, 1, 1, width).setValues([row.concat(Array(width - row.length).fill(""))]);
  SpreadsheetApp.flush();
}

// Returns section index -> {savedAt, rows}; a damaged staged section is treated as missing.
function marketingReadStaged_(job) {
  const staged = new Map();
  const sheet = SpreadsheetApp.openById(SPREADSHEET_DATA_EXTRACTION).getSheetByName(MARKETING_STAGING_SHEET);
  if (!sheet || sheet.getLastRow() < 2) return staged;
  const key = marketingStagingKey_(job);
  sheet.getRange(2, 1, sheet.getLastRow() - 1, sheet.getLastColumn()).getValues().forEach(row => {
    if (row[0] !== key) return;
    try {
      const chunks = row.slice(4).filter(value => value !== "");
      if (!chunks.length || chunks.some(value => !String(value).startsWith("b64:"))) throw new Error("bad chunk");
      const json = Utilities.newBlob(Utilities.base64Decode(chunks.map(value => String(value).slice(4)).join("")))
        .getDataAsString("UTF-8");
      const rows = JSON.parse(json);
      if (!Array.isArray(rows) || rows.length !== Number(row[3])) throw new Error("bad record count");
      staged.set(Number(row[1]), {savedAt: Number(row[2]), rows: rows});
    } catch (error) {
      console.warn("Ignoring damaged staged section " + row[1] + " of " + job.fileId + ": " + error.message);
    }
  });
  return staged;
}

// Caller holds the script lock. Removes this file's staged sections from any job version.
function marketingDropStaged_(fileId) {
  const sheet = SpreadsheetApp.openById(SPREADSHEET_DATA_EXTRACTION).getSheetByName(MARKETING_STAGING_SHEET);
  if (!sheet || sheet.getLastRow() < 2) return;
  const width = sheet.getLastColumn();
  const values = sheet.getRange(1, 1, sheet.getLastRow(), width).getValues();
  const prefix = "job:" + fileId + ":";
  const keep = values.filter((row, i) => i === 0 || !String(row[0]).startsWith(prefix));
  if (keep.length === values.length) return;
  sheet.getRange(1, 1, keep.length, width).setValues(keep);
  sheet.getRange(keep.length + 1, 1, values.length - keep.length, width).clearContent();
}

// Counts page objects; 0 means unknown (for example compressed object streams).
function marketingPdfPageCount_(blob) {
  try {
    const text = blob.getDataAsString("ISO-8859-1");
    return (text.match(/\/Type\s*\/Page(?![a-zA-Z])/g) || []).length;
  } catch (error) {
    return 0;
  }
}

// The final range is open-ended so an undercounted page total never drops pages.
function marketingPageRanges_(pages) {
  const known = pages > 0 ? pages : MARKETING_PAGES_PER_REQUEST * MARKETING_MAX_RANGES;
  const count = Math.min(MARKETING_MAX_RANGES, Math.max(1, Math.ceil(known / MARKETING_PAGES_PER_REQUEST)));
  const size = Math.ceil(known / count);
  return Array.from({length: count}, (_, i) => ({
    first: i * size + 1, last: i === count - 1 ? null : (i + 1) * size
  }));
}

