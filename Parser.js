/**
 * Checks for docx files in the folder (input files folder)
 * Then converts them to pdfs, with the old docx reports moving to targetFolder.
 */
function checkForDocxFiles(folder, targetFolder){
  /**
   * Convert any potential docx files...
   */
  const filesToConvert = folder.getFilesByType(MimeType.MICROSOFT_WORD);
  while (filesToConvert.hasNext()){
    const file = filesToConvert.next();
    convertDocxToPdf(file.getId(), file.getName().replace(/\.(docx?|DOCX?)$/, ""), targetFolder);
  }
}


/**
 * Docx to pdf converter script!
 * 
 * fileId - file id to change from docx to pdf.
 * docName - name of the document without .docx
 * targetFolder - name of the folder to move the parsed docx to when turned to a pdf.
 */
function convertDocxToPdf(fileId, docName, targetFolder) {
  const file = DriveApp.getFileById(fileId);
  const parent = file.getParents().next();

  let pdfBlob;

  try {
    // Try direct DOCX → PDF export
    const url = `https://www.googleapis.com/drive/v3/files/${fileId}/export?mimeType=application/pdf&alt=media`;
    const token = ScriptApp.getOAuthToken();
    const response = trackedFetch("Google Drive API", url, {
      headers: { Authorization: `Bearer ${token}` }
    });

    pdfBlob = response.getBlob();
  } catch (e) {
    // Fallback: convert DOCX → Google Doc → PDF
    const gdoc = Drive.Files.copy(
      { mimeType: "application/vnd.google-apps.document" },
      fileId
    );

    const url = `https://www.googleapis.com/drive/v3/files/${gdoc.id}/export?mimeType=application/pdf&alt=media`;
    const token = ScriptApp.getOAuthToken();
    const response = trackedFetch("Google Drive API", url, {
      headers: { Authorization: `Bearer ${token}` }
    });

    pdfBlob = response.getBlob();

    DriveApp.getFileById(gdoc.id).setTrashed(true);
  }

  pdfBlob.setName(docName + ".pdf");

  const pdfFile = parent.createFile(pdfBlob);

  targetFolder.addFile(file);
  parent.removeFile(file);

  return pdfFile.getId();
}

