// One-shot extraction used by parseUndefinedFile: every section must succeed.
function geminiParsePDFUndefined(blob) {
  const source = marketingPdfSource_(blob);
  const sections = [];
  for (const range of marketingPageRanges_(source.pageCount)) {
    const response = marketingRequestSection_(marketingSectionPayload_(source, range), range);
    if (!marketingCompleteResponse_(response)) return response;
    sections.push(marketingResponseRows_(response, "page " + range.first));
  }
  return marketingJsonResponse_(marketingCombineSections_(sections));
}

const MARKETING_PAGES_PER_REQUEST = 4;
const MARKETING_MAX_RANGES = 8;
const MARKETING_TRANSIENT_CODES = [429, 500, 502, 503, 504];
// Documented UrlFetchApp option (default 360 s); one slow request cannot consume a whole execution.
const MARKETING_GEMINI_TIMEOUT_SECONDS = 90;
// A request starts only if it would time out by this point of the execution, leaving
// the remainder of the six-minute limit for import, identity review and the output tab.
const MARKETING_REQUEST_DEADLINE_MS = 240000;
const MARKETING_MAX_SECTION_ATTEMPTS = 6;
const MARKETING_STAGING_SHEET = "MA_Section_Staging";
const MARKETING_STAGING_HEADERS = ["Job Key", "Section", "Saved At (ms)", "Records", "Data"];
const MARKETING_STAGING_CHUNK = 40000;
// The key travels only in the x-goog-api-key header: UrlFetchApp timeout and network
// errors echo the request URL, so a ?key= query string would leak into logs.
const MARKETING_GEMINI_URL = String(GEMINI_URL).split("?")[0];

// Dispatches to the configured provider (MarketingExtractionProvider.js); no fallback.
// `payload` is {data, scope} from marketingSectionPayload_, or the whole PDF as base64.
function marketingRequestSection_(payload, range) {
  payload = marketingPayload_(payload, range);
  const provider = marketingExtractionProvider_();
  if (provider.name === "openai") return marketingOpenAIRequestSection_(payload, range, provider);
  API_CALL_INVENTORY["Gemini"] = (API_CALL_INVENTORY["Gemini"] || 0) + 1;
  const started = Date.now();
  let response;
  try {
    response = marketingGeminiFetch_(payload, range);
  } catch (error) {
    marketingRecordExtractionUsage_("Gemini", "", Date.now() - started, null);
    throw error;
  }
  let usage = null;
  try {
    const meta = JSON.parse(response.getContentText()).usageMetadata;
    if (meta) usage = {input: meta.promptTokenCount, output: meta.candidatesTokenCount, reasoning: meta.thoughtsTokenCount};
  } catch (error) {}
  marketingRecordExtractionUsage_("Gemini", "", Date.now() - started, usage);
  return response;
}

function marketingGeminiFetch_(payload, range) {
  payload = marketingPayload_(payload, range);
  return UrlFetchApp.fetch(MARKETING_GEMINI_URL, {
    method: "post",
    contentType: "application/json",
    headers: { "x-goog-api-key": GEMINI_API_KEY },
    muteHttpExceptions: true,
    timeoutSeconds: MARKETING_GEMINI_TIMEOUT_SECONDS,
    payload: JSON.stringify({
      contents: [{ parts: [
        { text: marketingExtractionPrompt_() + " " + payload.scope },
        { inline_data: { mime_type: "application/pdf", data: payload.data } }
      ] }],
      generationConfig: {
        responseMimeType: "application/json",
        thinkingConfig: { thinkingLevel: "low" }
      }
    })
  });
}

// Returns the extracted JSON array; throws when the response is incomplete or malformed.
function marketingResponseRows_(response, label) {
  if (!marketingCompleteResponse_(response)) throw new Error("Incomplete PDF extraction: " + label);
  const candidate = JSON.parse(response.getContentText()).candidates[0];
  const text = (candidate.content.parts || []).map(part => part.text || "").join("").trim();
  const rows = JSON.parse(text.replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "") || "[]");
  if (!Array.isArray(rows)) throw new Error("No report rows returned: " + label);
  return rows;
}

/**
 * Resumable report job used by the timer. Each page section is requested without
 * the script lock, bounded by timeoutSeconds, validated, and saved immediately to
 * the staging tab. A failed section waits with backoff while other sections and
 * reports continue. The report tab, contact import and archive run once every
 * section is saved, through the same checkpointed finalization as before.
 */
function marketingProcessReport_(file, blobFn, targetFolder, run) {
  const outcome = {state: "pending", failed: 0, deferred: false};
  const fileId = file.getId();
  if (PropertiesService.getScriptProperties().getProperty("MA_REPORT_" + fileId)) {
    const resumeDigest = marketingDigest_(file.getBlob().getBytes());
    marketingWithLock_(() => {
      marketingAssertOwner_(run);
      marketingResumeCheckpoint_(file, targetFolder, resumeDigest);
      marketingDropJob_(fileId);
    });
    outcome.state = "processed";
    return outcome;
  }
  let job = marketingLoadJob_(fileId);
  if (!job) {
    // An identical report uploaded as a new Drive file reuses the earlier import.
    const digest = marketingDigest_(file.getBlob().getBytes());
    const original = marketingContentOriginal_(digest, fileId);
    if (original) {
      marketingWithLock_(() => {
        marketingAssertOwner_(run);
        PropertiesService.getScriptProperties().setProperty("MA_REPORT_" + fileId, JSON.stringify(
          {sheetId: original.sheetId, state: "IMPORTED", duplicateOf: original.fileId}));
        file.moveTo(targetFolder);
      });
      console.log("Skipped " + file.getName() + " (" + fileId + "): identical content was already imported from " +
        original.fileId + "; no extraction or import was repeated.");
      outcome.state = "processed";
      return outcome;
    }
    if (marketingContentInProgress_(digest, fileId)) {
      console.log("Deferred " + file.getName() + ": identical content is still being extracted from another file.");
      outcome.deferred = true;
      return outcome;
    }
  }
  let source = null;
  // Loads the report once per visit; a new or changed file gets a fresh job.
  const load = () => {
    if (source) return source;
    const digest = marketingDigest_(file.getBlob().getBytes());
    const blob = blobFn();
    source = marketingPdfSource_(blob);
    if (!job || job.digest !== digest) {
      job = {fileId: fileId, digest: digest, createdAt: Date.now(),
        sections: marketingPageRanges_(source.pageCount).map(range => ({
          first: range.first, last: range.last, done: false, failed: false,
          attempts: 0, nextAt: 0, error: ""
        }))};
      marketingWithLock_(() => {
        marketingAssertOwner_(run);
        marketingDropStaged_(fileId);
        marketingSaveJob_(job);
      });
    }
    return source;
  };
  if (!job) {
    if (!marketingCanRequest_(run)) { outcome.deferred = true; return outcome; }
    load();
  }
  for (let i = 0; i < job.sections.length; i++) {
    const section = job.sections[i];
    if (section.done || section.failed || section.nextAt > Date.now()) continue;
    if (!marketingCanRequest_(run)) { outcome.deferred = true; break; }
    const pdf = load();
    if (job.sections[i] !== section) { i = -1; continue; }
    const label = file.getName() + " section " + (i + 1) + "/" + job.sections.length;
    let rows;
    const started = Date.now();
    const provider = marketingExtractionProvider_();
    try {
      const response = marketingRequestSection_(marketingSectionPayload_(pdf, section), section);
      const code = response.getResponseCode();
      if (code !== 200) {
        const error = new Error(provider.label + " HTTP " + code + " for " + label);
        error.permanent = !MARKETING_TRANSIENT_CODES.includes(code);
        throw error;
      }
      rows = marketingCleanReportRecords_(marketingResponseRows_(response, label));
    } catch (error) {
      if (marketingSplitSection_(run, job, i, error)) {
        logMarketingFailure_(provider.stage, fileId + "#" + (i + 1), error);
        i--;
        continue;
      }
      // Timeouts, network errors, HTTP 429/5xx and malformed output are retried later.
      outcome.failed++;
      marketingRecordSectionFailure_(run, job, i, error);
      logMarketingFailure_(provider.stage, fileId + "#" + (i + 1), error);
      continue;
    }
    console.log("Saved " + label + " (" + provider.label + "): " + rows.length + " records after " +
      Math.round((Date.now() - started) / 1000) + " s.");
    marketingWithLock_(() => {
      marketingAssertOwner_(run);
      marketingStageSection_(job, i, Date.now(), rows);
      section.done = true;
      section.provider = provider.label + (provider.model ? " " + provider.model : "");
      section.error = "";
      marketingSaveJob_(job);
    });
  }
  if (job.sections.some(section => section.failed)) { outcome.state = "blocked"; return outcome; }
  if (!job.sections.every(section => section.done)) return outcome;
  if (Date.now() - run.startedAt > MARKETING_REQUEST_DEADLINE_MS) { outcome.deferred = true; return outcome; }
  marketingWithLock_(() => {
    marketingAssertOwner_(run);
    const staged = marketingReadStaged_(job);
    const missing = job.sections.map((_, i) => i).filter(i => !staged.has(i));
    if (missing.length) {
      missing.forEach(i => { job.sections[i].done = false; });
      marketingSaveJob_(job);
      throw new Error("Staged sections " + missing.map(i => i + 1).join(",") +
        " are missing and will be requested again: " + file.getName());
    }
    // Split halves are appended to the job, so combine in page order rather than index order.
    const order = job.sections.map((_, i) => i).sort((a, b) => job.sections[a].first - job.sections[b].first);
    const combined = marketingCombineSections_(order.map(i => staged.get(i).rows));
    if (!combined.length) {
      job.sections.forEach(section => Object.assign(section,
        {done: false, failed: true, error: "No report rows returned"}));
      marketingDropStaged_(fileId);
      marketingSaveJob_(job);
      throw new Error("No report rows returned: " + file.getName());
    }
    const extractedAt = new Date(Math.max(...[...staged.values()].map(entry => entry.savedAt))).toISOString();
    marketingFinalizeReport_(file,
      marketingWithProvenance_(file, marketingCleanReportRecords_(combined), extractedAt), targetFolder, job.digest);
    marketingDropJob_(fileId);
  });
  outcome.state = "processed";
  return outcome;
}

function marketingCanRequest_(run) {
  return Date.now() - run.startedAt + MARKETING_GEMINI_TIMEOUT_SECONDS * 1000 <= MARKETING_REQUEST_DEADLINE_MS;
}

/**
 * A multi-page section that times out or exceeds the output limit is halved instead
 * of retried whole: it keeps its first half and the second half is appended, so the
 * staged indexes of completed sections never shift. Single pages use normal backoff.
 */
function marketingSplitSection_(run, job, index, error) {
  const section = job.sections[index];
  const message = String(error && error.message || error);
  if (!(error && error.splittable) && !/\bTimeout\b/i.test(message)) return false;
  if (section.last === null || section.last <= section.first) return false;
  const mid = Math.floor((section.first + section.last) / 2);
  job.sections.push({first: mid + 1, last: section.last, done: false, failed: false,
    attempts: 0, nextAt: 0, error: "", splitFrom: section.first + "-" + section.last});
  Object.assign(section, {last: mid, attempts: 0, nextAt: 0,
    error: marketingRedact_(message).slice(0, 300)});
  marketingWithLock_(() => {
    marketingAssertOwner_(run);
    marketingSaveJob_(job);
  });
  console.log("Split pages " + section.first + "-" + job.sections[job.sections.length - 1].last +
    " of " + job.fileId + " into " + section.first + "-" + mid + " and " + (mid + 1) + "-" +
    job.sections[job.sections.length - 1].last + " after: " + marketingRedact_(message).slice(0, 120));
  return true;
}

function marketingRecordSectionFailure_(run, job, index, error) {
  const section = job.sections[index];
  section.attempts++;
  section.error = marketingRedact_(error && error.message || error).slice(0, 300);
  section.failed = !!(error && error.permanent) || section.attempts >= MARKETING_MAX_SECTION_ATTEMPTS;
  // Timer runs are five minutes apart: retry after about 5, 10, 20 and 40 minutes, then hourly.
  section.nextAt = Date.now() + (Math.min(60, 5 * Math.pow(2, section.attempts - 1)) - 1) * 60000;
  marketingWithLock_(() => {
    marketingAssertOwner_(run);
    marketingSaveJob_(job);
  });
}

